--
-- Impor penuh sekaligus (membuat database bila belum ada):
--   psql -f database.sql
-- Atau manual:
--   createdb topupku
--   psql -d topupku -f database.sql

CREATE TABLE users (
  id_user INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama VARCHAR(100) NOT NULL,
  email VARCHAR(100) NOT NULL UNIQUE,
  no_hp VARCHAR(15) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'pelanggan' CHECK (role IN ('admin', 'pelanggan')),
  status VARCHAR(20) NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif', 'nonaktif')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE categories (
  id_kategori INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_kategori VARCHAR(50) NOT NULL,
  deskripsi VARCHAR(255) NULL
);

CREATE TABLE products (
  id_produk INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_kategori INT NOT NULL REFERENCES categories(id_kategori),
  nama_produk VARCHAR(100) NOT NULL,
  provider VARCHAR(50) NOT NULL,
  nominal INT NOT NULL,
  harga_jual NUMERIC(12,2) NOT NULL,
  deskripsi TEXT NULL,
  gambar VARCHAR(255) NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif', 'nonaktif'))
);

CREATE TABLE voucher_stocks (
  id_stok INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_produk INT NOT NULL REFERENCES products(id_produk),
  kode_voucher VARCHAR(100) NOT NULL UNIQUE,
  status VARCHAR(20) NOT NULL DEFAULT 'tersedia' CHECK (status IN ('tersedia', 'terpakai')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE transactions (
  id_transaksi INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode_transaksi VARCHAR(20) NOT NULL UNIQUE,
  id_user INT NOT NULL REFERENCES users(id_user),
  id_produk INT NOT NULL REFERENCES products(id_produk),
  id_stok INT NULL REFERENCES voucher_stocks(id_stok) ON DELETE SET NULL,
  nomor_tujuan VARCHAR(50) NOT NULL,
  total_bayar NUMERIC(12,2) NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'menunggu_bayar' CHECK (status IN ('menunggu_bayar', 'menunggu_verifikasi', 'diproses', 'berhasil', 'gagal', 'dibatalkan')),
  hasil VARCHAR(255) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_transactions_status ON transactions(status);
CREATE INDEX idx_transactions_created_at ON transactions(created_at);

CREATE TABLE payments (
  id_pembayaran INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_transaksi INT NOT NULL UNIQUE REFERENCES transactions(id_transaksi),
  metode VARCHAR(20) NOT NULL CHECK (metode IN ('transfer_bank', 'e_wallet', 'qris')),
  jumlah NUMERIC(12,2) NOT NULL,
  bukti_bayar VARCHAR(255) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'menunggu' CHECK (status IN ('menunggu', 'terverifikasi', 'ditolak')),
  catatan VARCHAR(255) NULL,
  diverifikasi_oleh INT NULL REFERENCES users(id_user),
  waktu_bayar TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  waktu_verifikasi TIMESTAMP NULL
);

-- Pengganti ON UPDATE CURRENT_TIMESTAMP dari MySQL
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_transactions_updated_at
BEFORE UPDATE ON transactions
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

